lista = ["a", "b", "c", "d", "e", "f", "g"]

print(lista[0:len(lista)]) # Lista Entera Principio Fin

print(lista[:]) # Lista Entera Principio Fin

print(lista[-1]) # g Empiza final en numeros negativos

print(lista[-len(lista)]) # a Empiza Valor 0

print(lista[-len(lista):]) # Lista Entera Principio Fin

print(lista[:len(lista)]) # Lista Entera Principio Fin

print(lista[len(lista)-1]) # g Empiza final en numeros negativos

print(lista[len(lista):0:-1]) # Lista inversa excluyendo el 0

print(lista[::-1]) # Lista inversa